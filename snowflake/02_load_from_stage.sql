-- =====================================================================
-- Load CSVs into LUMORA.RAW WITHOUT local Python.
-- Step 1: run section A. Step 2: upload the 8 CSVs to the stage in Snowsight.
-- Step 3: run section B. Re-runnable: tables are recreated each time.
-- RAW keeps every column as text; dbt staging casts types (Day 2).
-- =====================================================================
USE ROLE SYSADMIN;
USE WAREHOUSE LUMORA_WH;
USE SCHEMA LUMORA.RAW;

-- ---------- A) file format + stage (run first) ----------
CREATE FILE FORMAT IF NOT EXISTS CSV_RAW
  TYPE = CSV
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = TRUE;

CREATE STAGE IF NOT EXISTS RAW_STAGE FILE_FORMAT = CSV_RAW;

-- Now upload the CSV files to RAW_STAGE in Snowsight, then run section B.
-- Check the upload worked:
LIST @RAW_STAGE;

-- ---------- B) tables + COPY (run after upload) ----------
CREATE OR REPLACE TABLE RAW_CUSTOMERS (
  CUSTOMER_ID VARCHAR,
  COMPANY_NAME VARCHAR,
  COUNTRY_CODE VARCHAR,
  REGION VARCHAR,
  INDUSTRY VARCHAR,
  SEGMENT VARCHAR,
  ACQUISITION_CHANNEL VARCHAR,
  SIGNUP_DATE VARCHAR,
  SALES_REP_ID VARCHAR,
  _LOADED_AT TIMESTAMP_NTZ
);
COPY INTO RAW_CUSTOMERS
  FROM (SELECT $1, $2, $3, $4, $5, $6, $7, $8, $9, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ FROM @RAW_STAGE/raw_customers.csv)
  FILE_FORMAT = (FORMAT_NAME = CSV_RAW);

